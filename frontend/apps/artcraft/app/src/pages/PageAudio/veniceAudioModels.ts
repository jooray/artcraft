const VENICE_AUDIO_MODEL_IDS = new Set(VENICE_AUDIO_MODELS.map((model) => model.model));

/** Whether the (API) model id is served by Venice directly. */
export const isVeniceAudioModel = (modelId: string | null | undefined): boolean =>
  !!modelId && VENICE_AUDIO_MODEL_IDS.has(modelId);

/** Append the Venice models the backend listing does not know about. */
export const withVeniceAudioModels = (
  models: OmniGenAudioModelDetails[],
): OmniGenAudioModelDetails[] => {
  const known = new Set(models.map((model) => model.model));
  return [...models, ...VENICE_AUDIO_MODELS.filter((model) => !known.has(model.model))];
};
